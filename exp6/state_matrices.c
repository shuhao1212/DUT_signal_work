void state_matrices(double A[2][2], double B[2], double C[2], double *D)
{
    /* 固定差分方程系数：y[n] = 0.180000*y[n-1] - 0.130000*y[n-2] + 1.000000*x[n] */
    A[0][0] = 0.180000;
    A[0][1] = -0.130000;
    A[1][0] = 1.0;
    A[1][1] = 0.0;

    B[0] = 1.0;
    B[1] = 0.0;

    C[0] = 1.0;
    C[1] = 0.0;

    *D = 0.0;
}
